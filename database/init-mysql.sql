-- MySQL 8.0；在 Workbench 中执行。不会删除已有表或数据。
CREATE DATABASE IF NOT EXISTS campus_lost_found CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE campus_lost_found;
CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 student_number VARCHAR(30) NOT NULL UNIQUE,
 name VARCHAR(50) NOT NULL,
 phone VARCHAR(11) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL,
 role VARCHAR(16) NOT NULL DEFAULT 'user',
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS category (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(50) NOT NULL UNIQUE,
 sort_no INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS item (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 category_id BIGINT NOT NULL,
 title VARCHAR(100) NOT NULL,
 type VARCHAR(10) NOT NULL,
 location VARCHAR(100) NOT NULL,
 occurred_at TIMESTAMP NOT NULL,
 description TEXT NOT NULL,
 contact VARCHAR(100) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'open',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 finished_at TIMESTAMP NULL,
 CONSTRAINT fk_item_user FOREIGN KEY(user_id) REFERENCES app_user(id),
 CONSTRAINT fk_item_category FOREIGN KEY(category_id) REFERENCES category(id)
);
CREATE TABLE IF NOT EXISTS claim (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 item_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL,
 description TEXT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending',
 reply VARCHAR(500),
 reviewer_id BIGINT NULL,
 publisher_status VARCHAR(16) NOT NULL DEFAULT 'pending',
 publisher_reply VARCHAR(500),
 publisher_confirmed_at TIMESTAMP NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reviewed_at TIMESTAMP NULL,
 CONSTRAINT uq_claim_user_item UNIQUE(item_id,user_id),
 CONSTRAINT fk_claim_item FOREIGN KEY(item_id) REFERENCES item(id) ON DELETE CASCADE,
 CONSTRAINT fk_claim_user FOREIGN KEY(user_id) REFERENCES app_user(id),
 CONSTRAINT fk_claim_reviewer FOREIGN KEY(reviewer_id) REFERENCES app_user(id)
);
CREATE TABLE IF NOT EXISTS notice (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 publisher_id BIGINT NOT NULL,
 item_id BIGINT NULL,
 category_id BIGINT NULL,
 title VARCHAR(100) NOT NULL,
 content TEXT NOT NULL,
 kind VARCHAR(16) NOT NULL DEFAULT 'system',
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 published_at TIMESTAMP NOT NULL,
 starts_at TIMESTAMP NOT NULL,
 expires_at TIMESTAMP NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_notice_publisher FOREIGN KEY(publisher_id) REFERENCES app_user(id),
 CONSTRAINT fk_notice_item FOREIGN KEY(item_id) REFERENCES item(id) ON DELETE SET NULL,
 CONSTRAINT fk_notice_category FOREIGN KEY(category_id) REFERENCES category(id)
);
